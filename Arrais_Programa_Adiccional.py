
# Presentamos nuestro super conversor de temperatura
print("CONVERSOR DE TEMPERATURA")

# Pedimos los grados Celsius
celsius = float(input("Ingresa los grados Celsius: "))

# Aplicamos la formula y dejamos que Python haga las cuentas
fahrenheit = (celsius * 9 / 5) + 32

# Listo, aqui tenemos el resultado
print("Temperatura en Fahrenheit:", fahrenheit)
